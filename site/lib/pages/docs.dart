import 'package:jaspr/jaspr.dart';

import '../components/layout.dart';
import '../site.dart';

const _html = r'''
<p>Three kinds of documentation, for three kinds of reader.</p>
<h2 id="guides">Guides</h2>
<p>For people who want to set Ymir up and use it.</p>
<ul>
<li><a href="${guide}">Deployment guide</a>, start to finish:
  <ul>
  <li><a href="${guide}#install">1. Install Ymir</a> and start it as a service</li>
  <li><a href="${guide}#pool">2. Start a pool and add a device</a></li>
  <li><a href="${guide}#bragi">3. Connect Bragi</a></li>
  <li><a href="${guide}#jan">4. Use Jan through the local bridge</a></li>
  <li><a href="${guide}#https">5. Optional: an HTTPS address on a private network</a></li>
  </ul></li>
<li><a href="${quickstart}">Quickstart</a>, the one-box short version</li>
<li><a href="${hardware}">Hardware</a> Ymir runs on</li>
</ul>
<h2 id="api">API</h2>
<p>Reference documentation generated by <code>cargo doc</code> from the doc comments of the Ymir workspace crates, rebuilt
by the site workflow whenever the crate sources change.</p>
<ul>
<li><a href="${api}ymir_core/index.html"><code>ymir_core</code></a>: the node coordinator, roles, config, setup, pool membership and control protocol</li>
<li><a href="${api}ymirctl/index.html"><code>ymirctl</code></a>: the command-line front end</li>
<li><a href="${api}ymird/index.html"><code>ymird</code></a>: the node daemon</li>
<li><a href="${api}ymir_testkit/index.html"><code>ymir_testkit</code></a>: helpers for tests</li>
</ul>
<h2 id="develop">Develop</h2>
<p>For people who want to change Ymir. The <a href="${develop}">developer guide</a> covers building, the repository layout,
running the tests, how the roles fit together, contributing and releasing.</p>
''';

class DocsPage extends StatelessComponent {
  const DocsPage({super.key});

  @override
  Component build(BuildContext context) {
    return Component.fragment([
      pageHero(
        eyebrow: 'Docs',
        title: 'Documentation',
        lede: 'Guides to use Ymir, the API reference, and guides for developers.',
      ),
      prose(
        _html
            .replaceAll(r'${guide}', siteLink('/docs/guides/deployment'))
            .replaceAll(r'${quickstart}', siteLink('/quickstart'))
            .replaceAll(r'${hardware}', siteLink('/hardware'))
            .replaceAll(r'${api}', siteLink('/docs/api/'))
            .replaceAll(r'${develop}', siteLink('/docs/develop')),
      ),
    ]);
  }
}
