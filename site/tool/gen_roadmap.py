#!/usr/bin/env python3
"""Render roadmap.toml (repo root) to ROADMAP.md and site/lib/content/roadmap.dart.

    python3 tool/gen_roadmap.py          # rewrite both files
    python3 tool/gen_roadmap.py --check  # fail if either is out of date (CI)
"""
import sys, tomllib, pathlib

SITE = pathlib.Path(__file__).resolve().parent.parent
ROOT = SITE.parent
LABEL = {"done": "Done", "in-progress": "In progress", "planned": "Planned"}

def dq(s):  # Dart single-quoted string
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"

def render():
    d = tomllib.loads((ROOT / "roadmap.toml").read_bytes().decode())
    p, ms = d["project"], d["milestone"]
    for m in ms:
        assert m["status"] in LABEL, m["id"]
    md = [f"# {p['name']} roadmap", "",
          "<!-- Generated from roadmap.toml by site/tool/gen_roadmap.py. Edit roadmap.toml, not this file. -->", "",
          p["intro"], "", f"Updated {p['updated']}. Design: [docs/DESIGN.md]({p['design']}).", ""]
    for m in ms:
        md += [f"## {m['id']} {m['title']} ({LABEL[m['status']]})", "", m["summary"], ""]
        md.append("Weirdnet crates: " + (", ".join(f"`{c}`" for c in m["crates"]) if m["crates"] else "none new") + ".")
        md.append("")
        if m["gaps"]:
            md.append("Known gaps:")
            md += [f"- {g}" for g in m["gaps"]]
            md.append("")
    dart = ["// GENERATED by tool/gen_roadmap.py from ../roadmap.toml. Do not edit.", "",
            "class Milestone {",
            "  const Milestone(this.id, this.title, this.status, this.summary, this.crates, this.gaps);",
            "  final String id, title, status, summary;",
            "  final List<String> crates, gaps;",
            "}", "",
            f"const roadmapIntro = {dq(p['intro'])};",
            f"const roadmapUpdated = {dq(p['updated'])};",
            f"const roadmapDesignUrl = {dq(p['design'])};",
            "const unpublishedCrates = <String>[" + ", ".join(dq(c) for c in p.get("unpublished", [])) + "];", "",
            "const milestones = <Milestone>["]
    for m in ms:
        cs = ", ".join(dq(c) for c in m["crates"]); gs = ", ".join(dq(g) for g in m["gaps"])
        dart.append(f"  Milestone({dq(m['id'])}, {dq(m['title'])}, {dq(m['status'])}, {dq(m['summary'])}, [{cs}], [{gs}]),")
    dart.append("];")
    return "\n".join(md).rstrip() + "\n", "\n".join(dart) + "\n"

def main():
    md, dart = render()
    targets = {ROOT / "ROADMAP.md": md, SITE / "lib/content/roadmap.dart": dart}
    if "--check" in sys.argv:
        bad = [str(t) for t, c in targets.items() if not t.exists() or t.read_text() != c]
        if bad:
            sys.exit("out of date: " + ", ".join(bad) + " (run site/tool/gen_roadmap.py)")
        return
    for t, c in targets.items():
        t.parent.mkdir(parents=True, exist_ok=True); t.write_text(c)

main()
